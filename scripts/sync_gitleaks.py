def normalize(pat: str) -> str:
    """Rewrite one gitleaks (Go RE2) regex into an equivalent Python regex."""
    while True:
        stripped = _LEADING_LAZY.sub(r"\1", pat, count=1)
        if stripped == pat:
            break
        pat = stripped
    needs_i = "(?i)" in pat
    pat = pat.replace("(?i)", "")
    for posix, py in _POSIX_CLASSES.items():
        pat = pat.replace(posix, py)
    pat = pat.replace("\\z", "\\Z")
    return ("(?i)" if needs_i else "") + pat


def build(rules: list[dict]) -> tuple[list[tuple[str, str, tuple[str, ...]]], list[tuple[str, str]]]:
    out, skipped = [], []
    for r in rules:
        rid, rx = r.get("id", ""), r.get("regex", "")
        if not rx:
            continue  # path-only rules (e.g. pkcs12-file) have no content regex
        body = normalize(rx)
        try:
            re.compile(body)
        except re.error as e:
            skipped.append((rid, str(e)[:120]))
            continue
        keywords = tuple(sorted({k.lower() for k in r.get("keywords", [])}))
        out.append((rid, body, keywords))
    return out, skipped


def render(rules: list[dict]) -> str:
    out, skipped = build(rules)
    lines = [HEADER.rstrip("\n"), "GITLEAKS_PATTERNS = ["]
    for rid, pat, kws in out:
        lines.append(f"    ({rid!r}, {pat!r}, {kws!r}),")
    lines.append("]")
    lines.extend(["", "GITLEAKS_SKIPPED = ["])
    for rid, err in skipped:
        lines.append(f"    ({rid!r}, {err!r}),")
    lines.append("]")
    return "\n".join(lines) + "\n"


def load_toml(path: str | None) -> dict:
    import tomllib  # Python 3.11+; only needed to regenerate

    if path:
        return tomllib.loads(Path(path).read_text())
    try:
        raw = urllib.request.urlopen(TOML_URL, timeout=30).read()
    except OSError as e:
        sys.exit(f"sync_gitleaks: cannot fetch {TOML_URL}: {e}\n"
                 "Download it elsewhere and rerun with --toml <file>.")
    return tomllib.loads(raw.decode())


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--toml", help="local gitleaks.toml instead of fetching GITLEAKS_REF")
    ap.add_argument("--check", action="store_true",
                    help="compare with the committed file instead of writing it")
    a = ap.parse_args(argv)
    text = render(load_toml(a.toml).get("rules", []))
    if a.check:
        if OUT.read_text() != text:
            print(f"{OUT} is stale; rerun scripts/sync_gitleaks.py", file=sys.stderr)
            return 1
        print(f"{OUT} is up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
